-- 0085_ext_app_login_log_count.sql
--
-- 登录日志加「登录次数」字段（需求 3 追加，2026-10-04；配合工单 19）。
--
-- ## 语义变化：从「今天出现过」到「今天登录过几次」
--
-- 0084 的去重是 `ON CONFLICT (device_id, log_date) DO NOTHING`：同设备同一天只留
-- 一行、且不计数，只能回答「这台设备今天出现过」。新需求是「每个检查算一次登录，
-- 更新最后登录时间，登录次数 +1（0→1→2）」，于是这一行必须变成**可累加**的：
--   · INSERT 时 `login_count = 1`；
--   · 冲突时 `login_count = login_count + 1` 且 `login_at` 覆盖为最新一次。
-- 行数不变（仍是「每设备每天一行」，需求「每天为 1 次」未变），变的是这一行现在
-- 携带当天的次数与最后一次时间。
--
-- ## DEFAULT 1 而不是 0
--
-- 存量行（0084 期间写入）每一条都代表「至少出现过一次」，回填成 1 才诚实；
-- 回填 0 会在后台显示「出现过但登录 0 次」这种自相矛盾的行。
--
-- ## 顺带关闭 0084 的已知缺口（部分关闭，勿过度宣称）
--
-- 0084 的注释与 ADR-0002 都记着一条缺口：「写入点在身份验证之后，未登录启动 /
-- 只请求匿名 `/api/app/version` 的启动在本表没有任何痕迹」。
-- 本次把写入点从设备登记（`registerUserDevice`）移到匿名的 `GET /api/app/version`
-- （App 每次启动的那一次版本检查），于是：
--   ✅ **联网**的启动都会落一行（未登录时 `user_id` 为空）；
--   ❌ **完全离线**的启动仍无痕迹 —— 没有请求发出，服务端无从记录，
--      要覆盖需 App 本地排队后补报，本轮未做。
--
-- 0084 的注释已同步改写（它当时写的是「user_id 永不为 NULL」「DO NOTHING」，
-- 现已不成立；两个迁移都尚未提交，所以直接更正比留一段过时说明更好）。
--
-- ## 幂等
--
-- SQLite 的 ALTER TABLE 加列不是幂等语句（列已存在会报错），因此本文件依赖迁移框架
-- 「每个文件只应用一次」（`d1_migrations` 记录，见 `manage-cli` 的
-- `applyLocalMigrations`）。手动重放前需先确认该列不存在。

ALTER TABLE ext_app_login_log ADD COLUMN login_count INTEGER NOT NULL DEFAULT 1;
