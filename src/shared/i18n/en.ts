export type TranslationLeaf = string;

/**
 * Recursively map en's structure to a type whose leaf values are `string`
 * instead of en's literal values. Used to type-check the zh-CN resource so its
 * keys must match en exactly while its values may be any string.
 */
export type DeepStringify<Value> = Value extends string
  ? string
  : {readonly [Key in keyof Value]: DeepStringify<Value[Key]>};

export type TranslationKey = DeepStringify<typeof en>;
